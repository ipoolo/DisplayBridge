const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('bridge',{
  state:()=>ipcRenderer.invoke('bridge:state'),
  refresh:()=>ipcRenderer.invoke('bridge:refresh'),
  selfCheck:()=>ipcRenderer.invoke('bridge:self-check'),
  confirmVisible:id=>ipcRenderer.invoke('bridge:confirm-visible',id),
  saveProfile:(profile,revision)=>ipcRenderer.invoke('bridge:profile',profile,revision),
  preferences:preferences=>ipcRenderer.invoke('bridge:preferences',preferences),
  beginShortcutEdit:()=>ipcRenderer.invoke('bridge:shortcut-edit-begin'),
  endShortcutEdit:token=>ipcRenderer.invoke('bridge:shortcut-edit-end',token),
  onShortcutEditCancel:callback=>ipcRenderer.on('shortcut-edit:cancel',callback),
  keyboardProbe:requestAccess=>ipcRenderer.invoke('bridge:keyboard-probe',requestAccess),
  mouseProbe:requestAccess=>ipcRenderer.invoke('bridge:mouse-probe',requestAccess),
  execute:action=>ipcRenderer.invoke('bridge:execute',action),
  pairingCode:()=>ipcRenderer.invoke('bridge:pairing-code'),
  pair:details=>ipcRenderer.invoke('bridge:pair',details),
  unpair:id=>ipcRenderer.invoke('bridge:unpair',id),
  sync:()=>ipcRenderer.invoke('bridge:sync'),
  clipboardList:()=>ipcRenderer.invoke('bridge:clipboard-list'),
  clipboardRefresh:()=>ipcRenderer.invoke('bridge:clipboard-refresh'),
  clipboardPublish:()=>ipcRenderer.invoke('bridge:clipboard-publish'),
  clipboardCopy:(sourceId,itemId)=>ipcRenderer.invoke('bridge:clipboard-copy',sourceId,itemId),
  exportDiagnostics:()=>ipcRenderer.invoke('bridge:diagnostics'),
  exportShortcuts:()=>ipcRenderer.invoke('bridge:shortcuts-export'),
  openShortcutsImport:()=>ipcRenderer.invoke('bridge:shortcuts-import-open'),
  previewShortcutsImport:(data,mode)=>ipcRenderer.invoke('bridge:shortcuts-import-preview',data,mode),
  applyShortcutsImport:(data,mode)=>ipcRenderer.invoke('bridge:shortcuts-import-apply',data,mode),
  readPeerShortcuts:peerId=>ipcRenderer.invoke('bridge:shortcuts-peer-read',peerId),
  previewShortcutsSync:(data,selection,edits)=>ipcRenderer.invoke('bridge:shortcuts-sync-preview',data,selection,edits),
  applyShortcutsSync:(data,selection,edits)=>ipcRenderer.invoke('bridge:shortcuts-sync-apply',data,selection,edits),
  onChange:callback=>{const handler=(_,data)=>callback(data);ipcRenderer.on('bridge:changed',handler);return ()=>ipcRenderer.removeListener('bridge:changed',handler);}
});
